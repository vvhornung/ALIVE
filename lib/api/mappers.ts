// DB records → DTOs. Every field is copied explicitly (no spreads) so a new
// secret column can never leak into a response by accident.
import type { AllocationRecord, EventRecord, PaymentRecord, PromiseRecord } from "@/lib/db";
import { parseMinor, toDisplay, type Amount } from "@/lib/money";
import type {
  AllocationView,
  ApprovalView,
  MoneyView,
  PaymentView,
  PromiseView,
  PublicStatusView,
  RecordsPack,
  TimelineEntry,
} from "./types";

export const RECORDS_DISCLAIMER = "Records generated by ALIVE; not a legal or tax document.";

export function toMoneyView(amount: Amount): MoneyView {
  return {
    value: amount.value,
    assetCode: amount.assetCode,
    assetScale: amount.assetScale,
    display: toDisplay(amount),
  };
}

function promiseAmount(promise: PromiseRecord, value: string): MoneyView {
  return toMoneyView({ value, assetCode: promise.assetCode, assetScale: promise.assetScale });
}

function debitOf(promise: PromiseRecord, payment: PaymentRecord): MoneyView | null {
  return payment.debitValue === null ? null : promiseAmount(promise, payment.debitValue);
}

function receiveOf(payment: PaymentRecord): MoneyView | null {
  if (payment.receiveValue === null || payment.receiveAssetCode === null || payment.receiveAssetScale === null) {
    return null;
  }
  return toMoneyView({
    value: payment.receiveValue,
    assetCode: payment.receiveAssetCode,
    assetScale: payment.receiveAssetScale,
  });
}

/** Highest attempt per allocation. */
export function latestPayments(payments: PaymentRecord[]): Map<string, PaymentRecord> {
  const latest = new Map<string, PaymentRecord>();
  for (const p of payments) {
    const current = latest.get(p.allocationId);
    if (!current || p.attempt > current.attempt) latest.set(p.allocationId, p);
  }
  return latest;
}

function toPaymentView(promise: PromiseRecord, payment: PaymentRecord): PaymentView {
  return {
    attempt: payment.attempt,
    step: payment.step,
    debit: debitOf(promise, payment),
    receive: receiveOf(payment),
    error: payment.error,
    createdAt: payment.createdAt,
    completedAt: payment.completedAt,
  };
}

export function toAllocationView(
  promise: PromiseRecord,
  allocation: AllocationRecord,
  payment: PaymentRecord | undefined,
  appBaseUrl: string,
): AllocationView {
  return {
    id: allocation.id,
    label: allocation.label,
    recipientWallet: allocation.recipientWallet,
    amount: promiseAmount(promise, allocation.value),
    status: allocation.status,
    simulated: allocation.simulated,
    statusUrl: `${appBaseUrl}/status/${allocation.statusToken}`,
    payment: payment ? toPaymentView(promise, payment) : null,
  };
}

export function toPromiseView(
  promise: PromiseRecord,
  allocations: AllocationRecord[],
  payments: PaymentRecord[],
  appBaseUrl: string,
): PromiseView {
  const allocated = allocations.reduce((acc, a) => acc + parseMinor(a.value), 0n);
  const unallocated = parseMinor(promise.totalValue) - allocated;
  const latest = latestPayments(payments);
  return {
    id: promise.id,
    status: promise.status,
    atRisk:
      promise.status === "at_risk" && promise.atRiskReason
        ? { reason: promise.atRiskReason, simulated: promise.atRiskReason === "simulated_revocation" }
        : null,
    freelancer: { wallet: promise.freelancerWallet, name: promise.freelancerName },
    payerWallet: promise.payerWallet,
    amount: promiseAmount(promise, promise.totalValue),
    allocated: promiseAmount(promise, allocated.toString()),
    unallocated: promiseAmount(promise, (unallocated < 0n ? 0n : unallocated).toString()),
    dueAt: promise.dueAt,
    description: promise.description,
    invoiceRef: promise.invoiceRef,
    allocations: allocations.map((a) => toAllocationView(promise, a, latest.get(a.id), appBaseUrl)),
    createdAt: promise.createdAt,
    testMode: true,
  };
}

export function toApprovalView(promise: PromiseRecord): ApprovalView {
  return {
    promiseId: promise.id,
    freelancerName: promise.freelancerName,
    amount: promiseAmount(promise, promise.totalValue),
    dueAt: promise.dueAt,
    description: promise.description,
    invoiceRef: promise.invoiceRef,
    status: promise.status,
    reapprovalNeeded:
      promise.status === "at_risk" &&
      (promise.atRiskReason === "grant_revoked" || promise.atRiskReason === "rotation_failed"),
    testMode: true,
  };
}

export function toPublicStatusView(
  promise: PromiseRecord,
  allocation: AllocationRecord,
  payment: PaymentRecord | undefined,
): PublicStatusView {
  return {
    label: allocation.label,
    amount: promiseAmount(promise, allocation.value),
    status: allocation.status,
    simulated: allocation.simulated,
    freelancerName: promise.freelancerName,
    dueAt: promise.dueAt,
    payment: payment
      ? { step: payment.step, recipientAmount: receiveOf(payment), completedAt: payment.completedAt }
      : null,
    testMode: true,
    note: "Status reported by ALIVE's server. Test mode: play money on the Interledger test wallet.",
  };
}

// ---------- timeline ----------

type Payload = Record<string, unknown>;
const str = (v: unknown): string | undefined => (typeof v === "string" ? v : undefined);
const num = (v: unknown): number | undefined => (typeof v === "number" ? v : undefined);

/** Human summaries built from known fields only; raw payloads never leave the server. */
export function toTimeline(
  promise: PromiseRecord,
  events: EventRecord[],
  allocations: AllocationRecord[],
  payments: PaymentRecord[],
): TimelineEntry[] {
  const labelByAllocation = new Map(allocations.map((a) => [a.id, a.label]));
  const allocationByPayment = new Map(payments.map((p) => [p.id, p.allocationId]));
  const total = toDisplay({ value: promise.totalValue, assetCode: promise.assetCode, assetScale: promise.assetScale });

  return events.map((event) => {
    const p: Payload = event.payload && typeof event.payload === "object" ? (event.payload as Payload) : {};
    const allocationId = str(p.allocationId) ?? allocationByPayment.get(str(p.paymentId) ?? "");
    const label = (allocationId && labelByAllocation.get(allocationId)) || "a recipient";
    return { type: event.type, at: event.at, summary: summarize(event.type, p, label, total) };
  });
}

function summarize(type: string, p: Payload, label: string, total: string): string {
  switch (type) {
    case "promise_created":
      return `Promise created for ${total}`;
    case "approval_requested":
      return "Approval link ready for the payer";
    case "authorization_started":
      return "Payer started the approval on their wallet";
    case "reapproval_started":
      return "Payer started a new approval";
    case "payer_approved":
      return "Payer approved on their wallet";
    case "reapproved":
      return "Payer approved again";
    case "payer_rejected":
      return "Payer declined the approval";
    case "hash_mismatch":
      return "Approval callback could not be fully verified (accepted in test mode)";
    case "allocations_replaced":
      return `Allocations updated (${num(p.count) ?? 0})`;
    case "execution_started":
      return "Payment day started";
    case "execution_retried":
      return "Payment day retried";
    case "execution_recovered":
      return "Interrupted payment day resumed";
    case "token_rotated":
      return "Payer authorization refreshed";
    case "grant_revoked":
      return "Payer authorization was revoked; the payer must approve again";
    case "rotation_failed":
      return "Could not refresh the payer authorization; the payer must approve again";
    case "revocation_simulated":
      return "Revocation simulated (demo)";
    case "revocation_cleared":
      return "Simulated revocation cleared (demo)";
    case "payment_created":
      return `Payment attempt ${num(p.attempt) ?? 1} started for ${label}`;
    case "payment_incoming_created":
      return `Receiving side ready for ${label}`;
    case "payment_quoted":
      return `Quote for ${label}: payer pays ${str(p.debit) ?? "?"}, recipient gets ${str(p.receive) ?? "?"}`;
    case "quote_refreshed":
      return `Quote refreshed for ${label}`;
    case "payment_submitted":
      return `Payment sent to ${label}`;
    case "payment_adopted":
      return `Payment to ${label} was already sent; resumed it`;
    case "payment_completed":
      return `${label} received ${str(p.received) ?? "the payment"}`;
    case "payment_failed":
      return `Payment to ${label} failed`;
    case "payment_timeout":
      return `Still waiting for confirmation of the payment to ${label}`;
    case "payment_unresolved":
      return `Payment to ${label} is unconfirmed; it will be checked again, never sent twice`;
    case "allocation_paying":
      return `${label}: paying`;
    case "allocation_retried":
      return `${label}: retrying`;
    case "allocation_paid":
      return `${label}: paid`;
    case "allocation_failed":
      return `${label}: failed`;
    case "execution_completed":
      return `Payment day completed: ${num(p.paid) ?? "all"} of ${num(p.total) ?? "all"} paid`;
    case "execution_partially_failed":
      return `Payment day finished: ${num(p.paid) ?? 0} of ${num(p.total) ?? 0} paid`;
    case "execution_error":
      return "Payment day stopped by an error";
    default:
      return type.replace(/_/g, " ");
  }
}

// ---------- records pack ----------

export function toRecordsPack(
  promise: PromiseRecord,
  allocations: AllocationRecord[],
  payments: PaymentRecord[],
  events: EventRecord[],
  now: Date = new Date(),
): RecordsPack {
  const labelByAllocation = new Map(allocations.map((a) => [a.id, a.label]));
  return {
    kind: "alive.records-pack",
    version: 1,
    generatedAt: now.toISOString(),
    testMode: true,
    disclaimer: RECORDS_DISCLAIMER,
    promise: {
      id: promise.id,
      status: promise.status,
      freelancer: { wallet: promise.freelancerWallet, name: promise.freelancerName },
      payerWallet: promise.payerWallet,
      amount: promiseAmount(promise, promise.totalValue),
      dueAt: promise.dueAt,
      description: promise.description,
      invoiceRef: promise.invoiceRef,
      createdAt: promise.createdAt,
    },
    allocations: allocations.map((a) => ({
      id: a.id,
      label: a.label,
      recipientWallet: a.recipientWallet,
      amount: promiseAmount(promise, a.value),
      status: a.status,
      simulated: a.simulated,
    })),
    payments: payments.map((p) => ({
      id: p.id,
      allocationId: p.allocationId,
      label: labelByAllocation.get(p.allocationId) ?? "",
      attempt: p.attempt,
      step: p.step,
      debit: debitOf(promise, p),
      receive: receiveOf(p),
      incomingPaymentUrl: p.incomingPaymentUrl,
      outgoingPaymentUrl: p.outgoingPaymentUrl,
      error: p.error,
      createdAt: p.createdAt,
      completedAt: p.completedAt,
    })),
    events: toTimeline(promise, events, allocations, payments),
  };
}

export const approvalUrlFor = (appBaseUrl: string, approvalToken: string): string =>
  `${appBaseUrl}/approve/${approvalToken}`;

export const dashboardUrlFor = (appBaseUrl: string, promiseId: string, freelancerKey: string): string =>
  `${appBaseUrl}/dashboard/${promiseId}#k=${freelancerKey}`;
